def classify_category(text: str) -> str:
    """
    タスクテキストからカテゴリ名を返す（当たった語や色も要るときは classify を使う）

    Args:
        text: タスクテキスト

    Returns:
        str: 設定にあるカテゴリ名
    """
    return classify(text).category
